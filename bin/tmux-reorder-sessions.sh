#!/bin/bash
#
# 歯抜けになった tmux のセッション番号を 0 から連番に振り直す
# （0, 1, 5, 7 -> 0, 1, 2, 3）。対象は数字で始まるセッション名のみ。
# アタッチ中のセッションの番号も変わる。.tmux.conf のフックから呼ばれる。

# 数字で始まるセッション名を取得して昇順にソート
# tmux ls: セッション一覧を表示
# grep -E '^[0-9]*:': 数字で始まる行のみ抽出
# cut -f1 -d':': コロンの前の部分（セッション名）を抽出
# sort: 数値順にソート
sessions=$(tmux ls | grep -E '^[0-9]*:' | cut -f1 -d':' | sort)

# 新しいセッション番号（0から開始）
new=0

# 各セッションを順に処理
for old in $sessions; do
  # セッション名を変更
  # -t: ターゲットセッション（変更元）
  # 第2引数: 新しいセッション名
  tmux rename -t $old $new

  # 新しいセッション番号をインクリメント
  ((new++))
done
